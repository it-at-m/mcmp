export const databaseDetails: DatabaseDetail[] = baseDatabaseDetails.map(
  (database) => ({
    ...database,
    ...sqlMetrics[database.id],
  })
);

export const databaseListItems: DatabaseListItem[] = databaseDetails.map(
  (database) => ({
    id: database.id,
    name: database.name,
    engine: database.engine,
    deploymentType: database.deploymentType,
    fqdn: database.fqdn,
  })
);

export function getDatabaseDetail(id?: number | null): DatabaseDetail | null {
  if (id === null || id === undefined) {
    return null;
  }
  return databaseDetails.find((database) => database.id === id) ?? null;
}
